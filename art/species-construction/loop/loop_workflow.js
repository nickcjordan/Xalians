// Majority of three readers per candidate, mapped back to better, same or worse against the baseline.
function readerVerdicts(cands, reads, regions) {
  const out = []
  for (const c of cands) {
    const per = {}
    for (const rid of regions) {
      let better = 0, worse = 0
      const reasons = []
      for (const r of reads) {
        // match on the assembly name: readers name a pack by its assembly ("assembled-2412") while the
        // runner records the pack folder (".../assembled-2412/reader-pack"), so a path-suffix match
        // found nothing in round 21 and every reader verdict was recorded as same with no reason
        const norm = s => String(s || '').replace(/\\/g, '/').replace(/\/+$/, '').toLowerCase()
        const asm = s => (norm(s).match(/assembled-\d+/g) || []).pop() || null
        const same = (a, b) => a && b && (asm(a) && asm(a) === asm(b) || norm(a).endsWith(norm(b)) || norm(b).endsWith(norm(a)))
        // round 22: a reader wrote its region as "R02 face: eyes, nose, muzzle and cheeks"; read the id from it
        const regionId = s => (String(s || '').match(/R\d+/) || [''])[0]
        const e = r && (r.packs || []).find(p => regionId(p.region) === rid && same(c.pack, p.pack))
        if (!e) continue
        // the candidate's side in the pack comes from the runner's key; the pack folder records it as key.json, read by the runner into c.keys
        const side = (c.keys || {})[rid] || 'B'
        if (e.choice === side) better++; else if (e.choice !== 'same') worse++
        reasons.push(e.reason)
      }
      per[rid] = { verdict: better >= 2 ? 'better' : worse >= 2 ? 'worse' : 'same', better, worse, reason: reasons.join(' | ') }
    }
    out.push({ cand: c, per, score: Object.values(per).reduce((t, v) => t + v.better - v.worse, 0) })
  }
  return out.sort((a, b) => b.score - a.score)
}
// Every candidate read worse on the order's region, by a majority and with no reader preferring it.
const rejectedAll = (ranked, rid) => ranked.length > 0 && ranked.every(x => x.per[rid] && x.per[rid].verdict === 'worse' && x.per[rid].better === 0)
const readerReasons = (ranked, rid) => ranked.map(x => `${x.cand.name}: ${(x.per[rid] && x.per[rid].reason) || ''}`).join(' || ').slice(0, 1500)
// The runner's measured line reads "R06 measured: 5 changed (3 newly passing, 1 newly failing); ...".
function measuredGain(line, rid) {
  const m = String(line || '').match(new RegExp(rid + ' measured: \\d+ changed \\((\\d+) newly passing, (\\d+) newly failing\\)'))
  return m ? Number(m[1]) - Number(m[2]) : 0
}
// A candidate every reader region calls the same, with no new seam and a net measured gain on the order's region.
function measuredTie(ranked, regions, rid) {
  const clean = ranked.filter(x => regions.every(r => x.per[r] && x.per[r].verdict === 'same' && x.per[r].worse === 0) && /no new seams/.test(x.cand.seams || ''))
    .map(x => ({ ...x, gain: measuredGain(x.cand.measured, rid) })).filter(x => x.gain > 0)
  return clean.sort((a, b) => b.gain - a.gain)[0] || null
}
