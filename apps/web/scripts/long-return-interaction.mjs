import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:4173/long-return');
  await page.locator('.lr-briefing-details > summary').click();
  assert(await page.locator('.lr-briefing-screen').isVisible());
  await page.locator('.lr-briefing-details > summary').click();
  await page.locator('.lr-setup-settings > summary').click();
  await page.locator('.lr-setup-settings').getByRole('button', { name: /Standard/ }).click();
  await page.locator('.lr-setup-settings').getByRole('button', { name: /Simple/ }).click();
  await page.locator('.lr-setup-settings > summary').click();
  await page.getByRole('button', { name: /Seal crew/i }).click();
  const resources = () => page.locator('.lr-wizard-resources').innerText();
  const initial = await resources();
  const rules = page.getByRole('button', { name: 'Game rules', exact: true });
  await rules.focus();
  await page.keyboard.press('Enter');
  const dialog = page.getByRole('dialog');
  await dialog.waitFor();
  await page.keyboard.press('Shift+Tab');
  assert(await dialog.evaluate(el => el.contains(document.activeElement)), 'Dialog must retain keyboard focus');
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Game rules');
  await page.locator('.lr-simple-scouts > button').first().click();
  assert.equal(await resources(), initial, 'Selecting scout is not an action');
  await page.getByRole('button', { name: /Stay together/ }).click();
  const route = page.locator('.lr-board-pick').first();
  await route.focus();
  await page.keyboard.press('Enter');
  assert.equal(await resources(), initial, 'Selecting route is not an action');
  const command = page.locator('.lr-simple-override input');
  await command.check();
  const preview = await page.locator('.lr-route-board').innerText();
  await route.click();
  assert(await command.isChecked(), 'Reselecting route must not discard command');
  assert.equal(await page.locator('.lr-route-board').innerText(), preview);
  await page.locator('.lr-lead-options > summary').click();
  await page.locator('.lr-lead-options button[aria-pressed="false"]').first().click();
  assert.equal(await resources(), initial, 'Changing lead must not consume energy');
  await page.getByRole('button', { name: /Cross now/ }).click();
  await page.getByRole('button', { name: /Continue to result/ }).click();
  const after = await resources();
  await page.reload();
  await page.getByRole('button', { name: /Resume expedition/i }).click();
  assert.equal(await resources(), after, 'Resuming preserves the settled resource transaction');
  assert(await page.locator('.lr-simple-result').count());
  assert.equal(await page.locator('.lr-wizard-chrome').evaluate(el => document.activeElement === el), true);
  assert.deepEqual(errors, []);
  console.log('Keyboard rules dialog, reversible choices, command retention, actual crossing and checkpoint resume passed.');
  await context.close();
  const customContext = await browser.newContext({ viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' });
  const custom = await customContext.newPage();
  custom.on('pageerror', e => errors.push(e.message));
  await custom.goto('http://127.0.0.1:4173/long-return');
  await custom.getByRole('button', { name: /Seal crew/i }).click();
  await custom.getByRole('button', { name: /Stay together/ }).click();
  await custom.locator('.lr-board-pick').first().click();
  await custom.getByRole('button', { name: /Advanced: customize/ }).click();
  assert(await custom.locator('.lr-wizard-chrome').evaluate(el => el === document.activeElement));
  await custom.locator('.lr-crew-member').filter({ hasText: 'Hippochamp' }).click();
  await custom.getByRole('button', { name: 'Assign Chromocat as support', exact: true }).click();
  await custom.locator('.lr-method-select').filter({ hasText: 'Climb the suspension frame' }).click();
  const detailsButton = custom.getByRole('button', { name: 'See calculation details for Climb the suspension frame', exact: true });
  await detailsButton.click();
  await custom.getByRole('dialog').waitFor();
  await custom.keyboard.press('Escape');
  await custom.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'See calculation details for Climb the suspension frame');
  await custom.getByRole('button', { name: /Cross now/ }).click();
  await custom.getByRole('button', { name: /Continue to result/ }).click();
  assert(await custom.locator('.lr-simple-result').isVisible());
  assert.deepEqual(errors, []);
  console.log('Custom lead/support/method crossing and calculation-dialog focus restoration passed.');
  await customContext.close();
} finally { await browser.close(); }
